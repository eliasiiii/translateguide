// UniversalTranslate.mm
// Hooks JSContext the same way PlatoGuide did, but targets ANY RPG Maker
// MV/MZ game instead of one specific app: it detects the engine generically
// (looking for $dataSystem / Utils.RPGMAKER_NAME, which every RPG Maker
// MV/MZ game defines) and installs universal_translate.js's JSON.parse hook.
//
// UNTESTED end to end. Builds on the same evaluateScript swizzle pattern
// already confirmed working against real game bundles (Plato's pool.zip), but
// this file itself has never been compiled or run.
#import <UIKit/UIKit.h>
#import <JavaScriptCore/JavaScriptCore.h>
#import <objc/runtime.h>
#include "UniversalTranslate_Swift.h"   // generated by swiftc -emit-objc-header-path (see build_mac.sh)
#include "universal_translate.inc"      // const char* kRuntimeSrc, generated from universal_translate.js

static IMP g_eval1, g_eval2;
static NSString *g_targetLang = @"ar";
static BOOL g_enabled = YES;
static BOOL g_sessionReady = NO;

static void InstallBridge(JSContext *ctx) {
    JSValue *native = [JSValue valueWithNewObjectInContext:ctx];
    native[@"translateBatch"] = ^(NSString *textsJSON, NSString *lang, JSValue *callback) {
        if (!g_enabled) { [callback callWithArguments:@[@"[]"]]; return; }
        [[TranslationBridge shared] translateBatchWithTextsJSON:textsJSON
                                                      completion:^(NSString *resultJSON) {
            dispatch_async(dispatch_get_main_queue(), ^{
                [callback callWithArguments:@[resultJSON ?: @"[]"]];
            });
        }];
    };
    ctx[@"__ptNative"] = native;
}

static BOOL LooksLikeRPGMaker(NSString *script) {
    // $dataSystem and DataManager are part of every RPG Maker MV/MZ core
    // script (rpg_managers.js / rmmz_managers.js), not any one game's own
    // code, so this check is engine-generic rather than per-title.
    return [script rangeOfString:@"DataManager.loadDataFile"].location != NSNotFound
        || [script rangeOfString:@"Utils.RPGMAKER_NAME"].location != NSNotFound;
}

static NSString *PatchIfNeeded(JSContext *ctx, NSString *script) {
    if (![script isKindOfClass:NSString.class] || script.length < 2000) return script;
    if ([script rangeOfString:@"pgInstallTranslateHook"].location != NSNotFound) return script; // our own injected code
    if (!LooksLikeRPGMaker(script)) return script;
    static BOOL installedOnce = NO;
    if (!installedOnce) {
        installedOnce = YES;
        InstallBridge(ctx);
        NSString *runtime = [NSString stringWithUTF8String:kRuntimeSrc];
        [ctx evaluateScript:runtime];
        [ctx evaluateScript:[NSString stringWithFormat:@"pgInstallTranslateHook(%@);",
                              [NSString stringWithFormat:@"\"%@\"", g_targetLang]]];
    }
    return script; // the data files themselves are untouched; JSON.parse does the work as they load
}

static JSValue *hook1(JSContext *self, SEL _cmd, NSString *script) {
    return ((JSValue*(*)(id, SEL, NSString*))g_eval1)(self, _cmd, PatchIfNeeded(self, script));
}
static JSValue *hook2(JSContext *self, SEL _cmd, NSString *script, NSURL *url) {
    return ((JSValue*(*)(id, SEL, NSString*, NSURL*))g_eval2)(self, _cmd, PatchIfNeeded(self, script), url);
}

// ---------------- minimal menu: on/off + target language ----------------
@interface UTWin : UIWindow @end
@implementation UTWin
- (UIView *)hitTest:(CGPoint)p withEvent:(UIEvent *)e {
    UIView *v = [super hitTest:p withEvent:e];
    return (v == self || v == self.rootViewController.view) ? nil : v;
}
@end

@interface UTVC : UIViewController
@property (nonatomic, strong) UIButton *btn;
@property (nonatomic, strong) UIView *panel;
@property (nonatomic, strong) UILabel *status;
@end

@implementation UTVC
- (void)viewDidLoad {
    [super viewDidLoad];
    self.btn = [UIButton buttonWithType:UIButtonTypeSystem];
    self.btn.frame = CGRectMake(12, 90, 46, 46);
    self.btn.backgroundColor = [UIColor colorWithWhite:0 alpha:0.65];
    self.btn.layer.cornerRadius = 23;
    [self.btn setTitle:@"AR" forState:UIControlStateNormal];
    [self.btn setTitleColor:UIColor.whiteColor forState:UIControlStateNormal];
    [self.btn addTarget:self action:@selector(toggle) forControlEvents:UIControlEventTouchUpInside];
    [self.view addSubview:self.btn];

    self.panel = [[UIView alloc] initWithFrame:CGRectMake(12, 144, 260, 110)];
    self.panel.backgroundColor = [UIColor colorWithWhite:0 alpha:0.78];
    self.panel.layer.cornerRadius = 12;
    self.panel.hidden = YES;
    [self.view addSubview:self.panel];

    UILabel *l = [[UILabel alloc] initWithFrame:CGRectMake(12, 12, 160, 24)];
    l.text = @"Auto-translate (AR)"; l.textColor = UIColor.whiteColor; l.font = [UIFont systemFontOfSize:14];
    [self.panel addSubview:l];
    UISwitch *sw = [[UISwitch alloc] initWithFrame:CGRectMake(184, 10, 51, 31)];
    sw.on = g_enabled;
    [sw addTarget:self action:@selector(flip:) forControlEvents:UIControlEventValueChanged];
    [self.panel addSubview:sw];

    self.status = [[UILabel alloc] initWithFrame:CGRectMake(12, 50, 236, 50)];
    self.status.numberOfLines = 3;
    self.status.font = [UIFont systemFontOfSize:11];
    self.status.textColor = [UIColor colorWithWhite:0.75 alpha:1];
    [self.panel addSubview:self.status];
}
- (void)toggle { self.panel.hidden = !self.panel.hidden; [self refresh]; }
- (void)flip:(UISwitch *)sw { g_enabled = sw.on; }
- (void)refresh {
    self.status.text = g_sessionReady
        ? @"on-device translation ready"
        : @"preparing translation session...\n(needs the Arabic language pack\ninstalled once in iOS Settings)";
}
@end

static void ShowMenu(void) {
    UIWindowScene *scene = nil;
    for (UIScene *sc in UIApplication.sharedApplication.connectedScenes)
        if ([sc isKindOfClass:UIWindowScene.class] && sc.activationState == UISceneActivationStateForegroundActive) { scene = (UIWindowScene *)sc; break; }
    if (!scene) { dispatch_after(dispatch_time(DISPATCH_TIME_NOW, NSEC_PER_SEC), dispatch_get_main_queue(), ^{ ShowMenu(); }); return; }
    static UTWin *win;
    win = [[UTWin alloc] initWithWindowScene:scene];
    win.windowLevel = UIWindowLevelAlert + 1;
    win.backgroundColor = UIColor.clearColor;
    win.rootViewController = [UTVC new];
    win.hidden = NO;
}

__attribute__((constructor)) static void UTInit(void) {
    Class c = JSContext.class;
    Method m1 = class_getInstanceMethod(c, @selector(evaluateScript:));
    Method m2 = class_getInstanceMethod(c, @selector(evaluateScript:withSourceURL:));
    if (m1) g_eval1 = method_setImplementation(m1, (IMP)hook1);
    if (m2) g_eval2 = method_setImplementation(m2, (IMP)hook2);
    dispatch_after(dispatch_time(DISPATCH_TIME_NOW, 2 * NSEC_PER_SEC), dispatch_get_main_queue(), ^{
        [[TranslationBridge shared] prepareWithSourceCode:@"en" targetCode:g_targetLang completion:^(BOOL ok) {
            g_sessionReady = ok;
        }];
        ShowMenu();
    });
}
